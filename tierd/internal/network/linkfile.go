package network

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// Persistent NIC naming and bond MAC pinning.
//
// The installer pins each NIC's name with a 00-net<N>.link file. Older
// installers matched those files on MACAddress= alone, which udev compares
// against a device's *current* address. Bonds deliberately take a member's
// MAC (see MemberMAC; it keeps DHCP leases stable), and bond slaves take the
// bond's MAC, so a MACAddress=-only .link file also matches the bond. udev
// then renames bond0 to net0 at boot. The real NIC is left as eth1, and
// networkd can't enslave the bond to itself, so the box comes up with no
// address.
//
// PermanentMACAddress= matches the hardware's burned-in address. Bonds,
// VLANs and other software links have none, so they can never match.

// GenerateLinkFile generates a systemd .link file that pins a NIC's
// permanent (burned-in) MAC to a persistent interface name.
func GenerateLinkFile(name, mac string) string {
	var b strings.Builder
	b.WriteString("# Auto-generated by tierd. Do not edit.\n")
	fmt.Fprintf(&b, "[Match]\nPermanentMACAddress=%s\n\n", mac)
	fmt.Fprintf(&b, "[Link]\nName=%s\n", name)
	return b.String()
}

// MigrateLinkFilesToPermanentMAC rewrites .link files whose only [Match]
// selector is MACAddress= so they match PermanentMACAddress= instead. Files
// with any other selector (operator or custom rules) are left as they are.
// Returns the names of the rewritten files. udev reads .link files when a
// device appears, so the change takes effect on the next boot.
func MigrateLinkFilesToPermanentMAC(networkDir string) ([]string, error) {
	entries, err := os.ReadDir(networkDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var migrated []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".link") {
			continue
		}
		path := filepath.Join(networkDir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return migrated, err
		}
		updated, ok := permanentMACLinkFile(string(data))
		if !ok {
			continue
		}
		if err := writeFileAtomic(path, []byte(updated), 0644); err != nil {
			return migrated, fmt.Errorf("rewrite %s: %w", e.Name(), err)
		}
		migrated = append(migrated, e.Name())
	}
	sort.Strings(migrated)
	return migrated, nil
}

// ReconcileLinkFiles migrates MACAddress=-only .link files (see
// MigrateLinkFilesToPermanentMAC) and, when any changed, asks udev to reload
// its rules so a NIC that appears before the next boot uses the new match.
func ReconcileLinkFiles(networkDir string) ([]string, error) {
	migrated, err := MigrateLinkFilesToPermanentMAC(networkDir)
	if err != nil || len(migrated) == 0 {
		return migrated, err
	}
	if out, err := exec.Command("udevadm", "control", "--reload").CombinedOutput(); err != nil {
		return migrated, fmt.Errorf("udevadm control --reload: %w: %s", err, strings.TrimSpace(string(out)))
	}
	return migrated, nil
}

// permanentMACLinkFile returns content with its MACAddress= selector
// replaced, when [Match] has exactly that one selector.
func permanentMACLinkFile(content string) (string, bool) {
	lines := strings.Split(content, "\n")
	section := ""
	macLine := -1
	selectors := 0
	for i, raw := range lines {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = line
			continue
		}
		if section != "[Match]" {
			continue
		}
		selectors++
		key, value, found := strings.Cut(line, "=")
		if found && strings.TrimSpace(key) == "MACAddress" && strings.TrimSpace(value) != "" {
			macLine = i
		}
	}
	if macLine < 0 || selectors != 1 {
		return "", false
	}
	_, value, _ := strings.Cut(strings.TrimSpace(lines[macLine]), "=")
	lines[macLine] = "PermanentMACAddress=" + strings.TrimSpace(value)
	return strings.Join(lines, "\n"), true
}

func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmpName, perm); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}
