package network

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// BondConfig holds the desired configuration for a bond.
type BondConfig struct {
	Name      string          `json:"name"`
	Mode      string          `json:"mode"`       // "802.3ad", "balance-rr", "active-backup", etc.
	Members   []string        `json:"members"`    // interface names
	IPv4Addrs []string        `json:"ipv4_addrs"`
	IPv6Addrs []string        `json:"ipv6_addrs"`
	Gateway4  string          `json:"gateway4"`
	Gateway6  string          `json:"gateway6"`
	DHCP4     bool            `json:"dhcp4"`
	DHCP6     bool            `json:"dhcp6"`
	SLAAC     bool            `json:"slaac"`
	MTU       int             `json:"mtu"`
	DNS       []string        `json:"dns"`
	// Runtime values, as on Interface.
	CurrentGateway4 string   `json:"current_gateway4"`
	CurrentDNS      []string `json:"current_dns"`

	// MACAddress pins the bond's MAC (see MemberMAC). Left empty,
	// systemd-networkd generates one, which no DHCP server has seen.
	MACAddress string `json:"-"`
}

var validBondModes = map[string]bool{
	"802.3ad":       true,
	"balance-rr":    true,
	"active-backup": true,
	"balance-xor":   true,
	"balance-tlb":   true,
	"balance-alb":   true,
}

// ValidateBondMode checks if a bond mode is supported.
func ValidateBondMode(mode string) error {
	if !validBondModes[mode] {
		return fmt.Errorf("invalid bond mode: %s (must be 802.3ad, balance-rr, active-backup, balance-xor, balance-tlb, or balance-alb)", mode)
	}
	return nil
}

// ValidateBondName checks that a bond name is safe (e.g. "bond0").
func ValidateBondName(name string) error {
	if !strings.HasPrefix(name, "bond") {
		return fmt.Errorf("bond name must start with 'bond': %s", name)
	}
	return ValidateInterfaceName(name)
}

// GenerateBondNetdev generates a systemd-networkd .netdev file for a bond.
func GenerateBondNetdev(bond BondConfig) string {
	var b strings.Builder

	b.WriteString("# Auto-generated by tierd. Do not edit.\n")
	fmt.Fprintf(&b, "[NetDev]\nName=%s\nKind=bond\n", bond.Name)
	if bond.MACAddress != "" {
		fmt.Fprintf(&b, "MACAddress=%s\n", bond.MACAddress)
	}
	b.WriteString("\n")

	b.WriteString("[Bond]\n")
	fmt.Fprintf(&b, "Mode=%s\n", bond.Mode)

	if bond.Mode == "802.3ad" {
		b.WriteString("TransmitHashPolicy=layer3+4\n")
		b.WriteString("MIIMonitorSec=100ms\n")
		b.WriteString("LACPTransmitRate=fast\n")
	} else {
		b.WriteString("MIIMonitorSec=100ms\n")
	}

	return b.String()
}

// MemberMAC returns the permanent MAC of the first of members (in name
// order) that sysRoot (typically /sys/class/net) has one for, or "".
//
// A bond pinned to it keeps the address its first NIC had before it was
// bonded: the DHCP server sees the same client, the NIC leased an address
// on its own until the bond took over, and the bond keeps that address
// instead of being leased a new one on its first boot.
func MemberMAC(sysRoot string, members []string) string {
	sorted := append([]string(nil), members...)
	sort.Strings(sorted)
	for _, m := range sorted {
		// Member names reach here from the API: only a bare interface
		// name may become a path under sysRoot.
		if m == "" || strings.Contains(m, "..") || m != filepath.Base(m) {
			continue
		}
		// An enslaved NIC's address is the bond's; its own is perm_hwaddr.
		for _, f := range []string{"bonding_slave/perm_hwaddr", "address"} {
			data, err := os.ReadFile(filepath.Join(sysRoot, m, f))
			if mac := strings.TrimSpace(string(data)); err == nil && mac != "" && mac != "00:00:00:00:00:00" {
				return mac
			}
		}
	}
	return ""
}

// ExistingBondIdentity reads an existing bond's configured MAC and DHCP
// client identifier without inventing a new identity. Existing deployments
// must not be silently migrated to MemberMAC/ClientIdentifier=mac: that
// changes the DHCP client and can move the NAS to another address.
func ExistingBondIdentity(networkDir, bondName string) (mac, clientID string, err error) {
	if err = ValidateBondName(bondName); err != nil { return "", "", err }
	netdevNames := []string{"05-" + bondName + ".netdev"}
	networkNames := []string{"10-" + bondName + ".network"}
	if bondName == DefaultBondName {
		netdevNames = append(netdevNames, DefaultBondNetdevFilename)
		networkNames = append(networkNames, DefaultBondNetworkFilename)
	}
	for _, name := range netdevNames {
		data, readErr := os.ReadFile(filepath.Join(networkDir, name))
		if readErr != nil { if os.IsNotExist(readErr) { continue }; return "", "", readErr }
		mac = readINIValue(data, "NetDev", "MACAddress")
		break
	}
	for _, name := range networkNames {
		data, readErr := os.ReadFile(filepath.Join(networkDir, name))
		if readErr != nil { if os.IsNotExist(readErr) { continue }; return "", "", readErr }
		clientID = readINIValue(data, "DHCPv4", "ClientIdentifier")
		break
	}
	return mac, clientID, nil
}

func readINIValue(data []byte, section, key string) string {
	current := ""
	for _, raw := range strings.Split(string(data), "\\n") {
		line := strings.TrimSpace(raw)
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") { current = strings.Trim(line, "[]"); continue }
		if current != section || strings.HasPrefix(line, "#") { continue }
		k, v, ok := strings.Cut(line, "=")
		if ok && strings.TrimSpace(k) == key { return strings.TrimSpace(v) }
	}
	return ""
}

// GenerateBondMemberNetwork generates a .network file for a bond member interface.
func GenerateBondMemberNetwork(memberName, bondName string) string {
	var b strings.Builder

	b.WriteString("# Auto-generated by tierd. Do not edit.\n")
	fmt.Fprintf(&b, "[Match]\nName=%s\n\n", memberName)
	fmt.Fprintf(&b, "[Network]\nBond=%s\n", bondName)

	return b.String()
}

// GenerateBondNetwork generates a .network file for the bond interface itself.
func GenerateBondNetwork(bond BondConfig) string {
	// Reuse the interface config generator.
	cfg := InterfaceConfig{
		Name:      bond.Name,
		IPv4Addrs: bond.IPv4Addrs,
		IPv6Addrs: bond.IPv6Addrs,
		Gateway4:  bond.Gateway4,
		Gateway6:  bond.Gateway6,
		DHCP4:     bond.DHCP4,
		DHCP6:     bond.DHCP6,
		SLAAC:     bond.SLAAC,
		MTU:       bond.MTU,
		DNS:       bond.DNS,
	}
	return GenerateNetworkFile(cfg)
}
